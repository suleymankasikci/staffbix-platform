const REVERSE_SEGMENTS = Object.fromEntries(
  Object.entries(SEGMENTS).map(([locale, segments]) => [
    locale,
    Object.fromEntries(Object.entries(segments).map(([canonical, localized]) => [localized, canonical])),
  ])
) as Record<Locale, Record<string, string>>;

export function splitPath(pathname: string) {
  const [pathPart, hashPart] = pathname.split("#");
  const [basePath, queryPart] = pathPart.split("?");
  return {
    pathname: basePath || "/",
    suffix: `${queryPart ? `?${queryPart}` : ""}${hashPart ? `#${hashPart}` : ""}`,
  };
}

export function extractLocale(pathname: string): {
  locale: Locale | null;
  pathWithoutLocale: string;
} {
  const parts = pathname.split("/").filter(Boolean);
  const first = parts[0];
  if (!first || !isLocale(first)) {
    return { locale: null, pathWithoutLocale: pathname || "/" };
  }

  const rest = parts.slice(1).join("/");
  return { locale: first, pathWithoutLocale: rest ? `/${rest}` : "/" };
}

export function canonicalizePath(pathname: string, locale: Locale = DEFAULT_LOCALE) {
  const { pathname: cleanPath, suffix } = splitPath(pathname);
  const { locale: embeddedLocale, pathWithoutLocale } = extractLocale(cleanPath);
  const activeLocale = embeddedLocale ?? locale;
  const reverse = REVERSE_SEGMENTS[activeLocale] ?? {};
  const canonical = pathWithoutLocale
    .split("/")
    .filter(Boolean)
    .map((segment) => reverse[segment] ?? segment)
    .join("/");

  return `/${canonical}${suffix}`.replace(/^\/$/, "/");
}

export function localizePath(pathname: string, locale: Locale, includeLocale = true) {
  if (pathname.startsWith("http") || pathname.startsWith("mailto:")) return pathname;
  if (pathname.startsWith("#")) return pathname;

  const { pathname: cleanPath, suffix } = splitPath(pathname);
  const canonical = canonicalizePath(cleanPath, locale);
  const translated = canonical
    .split("/")
    .filter(Boolean)
    .map((segment) => SEGMENTS[locale]?.[segment] ?? segment)
    .join("/");

  const prefix = includeLocale ? `/${locale}` : "";
  return `${prefix}${translated ? `/${translated}` : ""}${suffix}` || `/${locale}`;
}
